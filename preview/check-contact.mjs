import assert from 'node:assert/strict';
import * as THREE from './node_modules/three/build/three.module.js';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('./contact.js',import.meta.url),'utf8')
 .replace("'three'",JSON.stringify(new URL('./node_modules/three/build/three.module.js',import.meta.url).href));
const {detectContact,contactVolumes,dropPathVolume,chooseDescentHeight}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(chooseDescentHeight(()=>false),.02);
assert.ok(chooseDescentHeight(h=>h<.04)>.04);
assert.throws(()=>chooseDescentHeight(()=>true),/待機位置/);
const person=new THREE.Group();
const face=new THREE.Mesh(new THREE.PlaneGeometry(.2,.2),new THREE.MeshBasicMaterial());
person.add(face);
const tool=new THREE.Mesh(new THREE.BoxGeometry(.02,.02,.02),new THREE.MeshBasicMaterial());
const parts=[{name:'ボトル',object:tool}];
tool.position.z=.1;
const before=contactVolumes(parts);
assert.equal(detectContact(person,before),null);
tool.position.z=0;
assert.equal(detectContact(person,contactVolumes(parts)).part,'ボトル');
tool.position.z=-.1;
assert.equal(detectContact(person,contactVolumes(parts)),null);
assert.equal(detectContact(person,contactVolumes(parts,before)).part,'ボトル');
face.position.x=1;
assert.equal(detectContact(person,contactVolumes(parts,before)),null);
face.position.set(0,.05,0);face.rotation.x=Math.PI/2;
assert.equal(detectContact(person,[dropPathVolume([0,.1,0],[0,0,0])]).part,'滴の経路');
face.position.x=1;
assert.equal(detectContact(person,[dropPathVolume([0,.1,0],[0,0,0])]),null);
console.log('接触・非接触・更新間の通り抜け・人物移動・滴経路の遮蔽: 合格');
